"""Optional TensorFlow / TFLite export path.

This script exists for the paper's stated deployment path (quantised .tflite on
TensorFlow Lite Micro).  It requires a Python version supported by TensorFlow
(3.10-3.12 at the time of writing); the rest of GridShield deliberately does
not depend on TensorFlow.

    python -m venv .venv-tflite
    .venv-tflite\\Scripts\\activate
    pip install "tensorflow-cpu==2.17.0"
    python ml/export_tflite.py

It rebuilds the exact NumPy architecture, loads the same weights, runs a short
fine-tune-free calibration pass for full-integer quantisation, and writes:

    models/gridshield_pqd.tflite
    firmware/arduino/gridshield_node/model_data.h

The firmware uses TFLite Micro automatically when ``model_data.h`` exists and
``-DUSE_TFLITE_MICRO`` is set in platformio.ini; otherwise it falls back to the
portable int8-weight kernels in ``ai.cpp`` which are numerically equivalent.
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np

from .cnn import CNN1D
from .config import (
    CLASSES,
    CONV1_FILTERS,
    CONV1_KERNEL,
    CONV2_FILTERS,
    CONV2_KERNEL,
    FIRMWARE_DIR,
    MODELS_DIR,
    POOL_SIZE,
    SEED,
    WEIGHTS_PATH,
    WINDOW,
)


def build_keras_model(model: CNN1D):
    import tensorflow as tf
    from tensorflow import keras
    from tensorflow.keras import layers

    inputs = keras.Input(shape=(WINDOW, 2), name="waveform")
    x = layers.Conv1D(CONV1_FILTERS, CONV1_KERNEL, padding="valid", activation="relu", name="conv1")(inputs)
    x = layers.MaxPooling1D(POOL_SIZE, name="pool1")(x)
    x = layers.Conv1D(CONV2_FILTERS, CONV2_KERNEL, padding="valid", activation="relu", name="conv2")(x)
    x = layers.MaxPooling1D(POOL_SIZE, name="pool2")(x)
    gap = layers.GlobalAveragePooling1D(name="gap")(x)
    gmp = layers.GlobalMaxPooling1D(name="gmp")(x)
    x = layers.Concatenate(name="concat")([gap, gmp])
    x = layers.Dense(32, activation="relu", name="dense1")(x)
    outputs = layers.Dense(len(CLASSES), activation="softmax", name="logits")(x)
    keras_model = keras.Model(inputs, outputs, name="gridshield_pqd_cnn")

    # Copy NumPy weights (K, C, F) -> Keras (K, C, F).
    keras_model.get_layer("conv1").set_weights([model.W1, model.b1])
    keras_model.get_layer("conv2").set_weights([model.W2, model.b2])
    keras_model.get_layer("dense1").set_weights([model.W3, model.b3])
    keras_model.get_layer("logits").set_weights([model.W4, model.b4])
    return keras_model


def representative_dataset():
    from .dataset import make_dataset

    x, _, _ = make_dataset(n_per_class=40, seed=SEED)
    for sample in x:
        yield [sample[None, ...].astype(np.float32)]


def export(weights: Path = WEIGHTS_PATH) -> tuple[Path, Path]:
    import tensorflow as tf
    from tensorflow import keras

    model = CNN1D.load(weights)
    keras_model = build_keras_model(model)
    keras_model.compile(optimizer="adam", loss="sparse_categorical_crossentropy", metrics=["accuracy"])

    converter = tf.lite.TFLiteConverter.from_keras_model(keras_model)
    converter.optimizations = [tf.lite.Optimize.DEFAULT]
    converter.representative_dataset = representative_dataset
    converter.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    converter.inference_input_type = tf.float32  # keep float I/O on the MCU
    converter.inference_output_type = tf.float32
    tflite_bytes = converter.convert()

    tflite_path = MODELS_DIR / "gridshield_pqd.tflite"
    tflite_path.write_bytes(tflite_bytes)

    header_path = FIRMWARE_DIR / "model_data.h"
    array = ", ".join(str(b) for b in tflite_bytes)
    header_path.write_text(
        "// AUTO-GENERATED by ml/export_tflite.py\n"
        "#pragma once\n"
        "#include <stdint.h>\n\n"
        f"const unsigned int g_model_len = {len(tflite_bytes)};\n"
        f"alignas(8) const uint8_t g_model[{len(tflite_bytes)}] = {{{array}}};\n",
        encoding="utf-8",
    )
    print(f"wrote {tflite_path} ({len(tflite_bytes)/1024:.1f} KB)")
    print(f"wrote {header_path}")

    # Sanity check with the TFLite interpreter.
    interpreter = tf.lite.Interpreter(model_content=tflite_bytes)
    interpreter.allocate_tensors()
    details = interpreter.get_input_details()[0]
    from .dataset import make_dataset

    x, y, _ = make_dataset(n_per_class=5, seed=123)
    correct = 0
    for sample, label in zip(x, y):
        interpreter.set_tensor(details["index"], sample[None, ...].astype(np.float32))
        interpreter.invoke()
        output = interpreter.get_tensor(interpreter.get_output_details()[0]["index"])
        correct += int(output.argmax() == label)
    print(f"TFLite int8 sanity accuracy on 25 windows: {correct/25:.2f}")
    return tflite_path, header_path


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--weights", type=Path, default=WEIGHTS_PATH)
    args = parser.parse_args(argv)
    export(args.weights)


if __name__ == "__main__":
    main()
